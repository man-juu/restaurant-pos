"""Core identity and tenancy tables (docs/05 section 2.1, FR-TEN-001, FR-TEN-002).

Conventions (docs/05 section 1): UUIDv7 primary keys generated by the server; every
tenant-owned table has tenant_id, a leading tenant_id index and RLS (see migrations);
critical references use composite (tenant_id, id) foreign keys so a row can never point at
another tenant's row; status columns are text with a CHECK constraint.
"""

import uuid
from datetime import datetime, time
from typing import Any, ClassVar

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Integer,
    MetaData,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import ARRAY, CITEXT, INET, JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app.core.ids import uuid7

# Stable constraint names make migrations reviewable and reversible.
NAMING = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING)
    # All timestamps are timestamptz (stored in UTC, FR-X-002).
    type_annotation_map: ClassVar[dict[Any, Any]] = {datetime: DateTime(timezone=True)}


def _id() -> Mapped[uuid.UUID]:
    return mapped_column(primary_key=True, default=uuid7)


def _created_at() -> Mapped[datetime]:
    return mapped_column(server_default=func.now())


def _check_in(column: str, values: tuple[str, ...]) -> CheckConstraint:
    quoted = ", ".join(f"'{v}'" for v in values)
    return CheckConstraint(f"{column} IN ({quoted})", name=f"{column}_valid")


TENANT_PROFILES = ("restaurant", "cloud_kitchen", "central_kitchen_group", "hybrid")
TENANT_STATUSES = ("active", "suspended", "deleted")
OUTLET_TYPES = ("restaurant", "branch", "cloud_kitchen", "central_kitchen", "warehouse")
USER_STATUSES = ("active", "disabled")
