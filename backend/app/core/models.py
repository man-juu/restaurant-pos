class User(Base):
    """Global identity: one person can belong to several tenants (FR-IDN-005). Not
    tenant-scoped, so no RLS; only the identity service touches it (slice 0.4)."""

    __tablename__ = "users"
    __table_args__ = (_check_in("status", USER_STATUSES),)

