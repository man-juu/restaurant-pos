class Tenant(Base):
    """FR-TEN-001. RLS: a tenant context sees only its own row (policy on id)."""

    __tablename__ = "tenants"
    __table_args__ = (
        _check_in("profile", TENANT_PROFILES),
        _check_in("status", TENANT_STATUSES),
        CheckConstraint("currency ~ '^[A-Z]{3}$'", name="currency_iso"),
        CheckConstraint("country ~ '^[A-Z]{2}$'", name="country_iso"),
    )

    id: Mapped[uuid.UUID] = _id()
    name: Mapped[str] = mapped_column(String(200))  # display name
    legal_name: Mapped[str] = mapped_column(String(200))
    country: Mapped[str] = mapped_column(String(2))
    currency: Mapped[str] = mapped_column(String(3))
    language: Mapped[str] = mapped_column(String(10))
    timezone: Mapped[str] = mapped_column(String(64))
    profile: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(Text, server_default="active")
    created_at: Mapped[datetime] = _created_at()


